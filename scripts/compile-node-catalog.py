#!/usr/bin/env python3
"""Generate the shared fixed node registry used by app and sysmodule."""
from pathlib import Path
import argparse
import hashlib
import json
import re
root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
raw=(root/'common/node-catalog.json').read_bytes()
catalog=json.loads(raw)
assert catalog['version']==1 and 1<=len(catalog['nodes'])<=32
nodes=catalog['nodes']; assert [n['id'] for n in nodes]==list(range(len(nodes)))
assert len({n['provider'] for n in nodes})==len(nodes)
for n in nodes:
    assert n['protocol'] in (0,1,2) and 1<=n['port']<=65535 and 0<=n['region']<=5
    assert re.fullmatch(r'[a-z0-9-]{1,32}',n['provider']) and re.fullmatch(r'[A-Za-z0-9.-]{1,95}',n['host'])
    assert n['country']=='' or re.fullmatch(r'[A-Z]{2}',n['country'])
    assert bool(n['country'])==n['region_verified'] and (not n['region_verified'] or n['regionEvidence'])
    assert all(0<len(n[k].encode())<64 for k in ('name_en','name_zh'))
header='''/* Generated by scripts/compile-node-catalog.py. SPDX-License-Identifier: GPL-2.0-only */
#pragma once
#include <stdint.h>

#define NODE_CATALOG_VERSION 1u
#define NODE_CATALOG_COUNT %du
#define NODE_ID_INVALID UINT32_MAX

enum NodeProtocol { NodeProtocolSelf=0, NodeProtocolLanywhere=1, NodeProtocolLanPlay=2 };
enum NodeRegion { NodeRegionUnknown=0, NodeRegionAsia=1, NodeRegionEurope=2, NodeRegionAmericas=3, NodeRegionOceania=4, NodeRegionAfrica=5 };
typedef struct {
    uint32_t id;
    uint32_t protocol;
    const char *provider;
    const char *host;
    uint16_t port;
    uint8_t region;
    uint8_t region_verified;
    const char *country;
    const char *name_en;
    const char *name_zh;
} LanywhereNode;
static const uint8_t LanywhereNodeCatalogHash[32] = {%s};
static const LanywhereNode LanywhereNodes[NODE_CATALOG_COUNT] = {
'''%(len(nodes),', '.join('0x%02x'%b for b in hashlib.sha256(raw).digest()))
for n in nodes:
    q=lambda s:json.dumps(s,ensure_ascii=False)
    header+='    {%du, %du, %s, %s, %du, %du, %du, %s, %s, %s},\n'%(n['id'],n['protocol'],q(n['provider']),q(n['host']),n['port'],n['region'],n['region_verified'],q(n['country']),q(n['name_en']),q(n['name_zh']))
header+='};\n'
output=root/'common/node_catalog.h'
if args.check:
    assert output.read_text()==header, 'Regenerate common/node_catalog.h'
else:output.write_text(header)
print('Node catalog verified',len(nodes),hashlib.sha256(raw).hexdigest())
